RATINGS_ZH = {"Buy": "买入", "Overweight": "增持", "Hold": "持有", "Underweight": "低配", "Sell": "卖出",
              "REVIEW": "待复核"}
BRAND = "QuantCouncil"


def _rating(value: str | None, lang: str) -> str:
    if not value:
        return "-"
    return f"{RATINGS_ZH.get(value, value)} {value}" if lang == "zh" else value


def _money(value: float | None) -> str:
    return "-" if value is None else f"{value:,.2f}"


def _pct(value: float | None) -> str:
    return "-" if value is None else f"{value * 100:.2f}%"


def _order_text(run: Run, t: dict) -> str:
    order = (run.risk_check or {}).get("order") if run.risk_check else None
    if not order or not (run.risk_check or {}).get("approved"):
        return t["none"]
    filled = (run.execution or {}).get("status") == "filled"
    side = t[order["side"]]
    return f"{side} {order['quantity']} @ {order['price']}" + ("" if filled else " (-)")


def _risk_blocks(check: dict | None, t: dict) -> list:
    if not check:
        return []
    items = [[(f"{t['blocked']}: ", True), (v["message"], False)] for v in check.get("violations", [])]
    items += [[(f"{t['warning']}: ", True), (w["message"], False)] for w in check.get("warnings", [])]
    order = check.get("order")
    blocks: list = [Heading(t["risk"], 3)]
    if order:
        blocks.append(text(f"{t[order['side']]} {order['quantity']} @ {order['price']}  "
                           f"({_pct(order['current_weight'])} -> {_pct(order['target_weight'])})", bold=True))
    if items:
        blocks.append(Bullets(items))
    return blocks


def daily_report(day: date, portfolio: PortfolioOut, runs: list[Run], orders: list[Order], lang: str = "zh") -> Report:
    t = L[lang]
    a = portfolio.account
    blocks: list = [
        Heading(t["account"], 1),
        Table(["", ""], [
            [t["equity"], _money(a.equity)], [t["cash"], _money(a.cash)],
            [t["market_value"], _money(a.market_value)], [t["pnl"], f"{_money(a.pnl)} ({_pct(a.pnl_pct)})"],
            [t["drawdown"], _pct(a.drawdown_pct)],
            [t["ledger"], t["ok"] if portfolio.ledger_verified else t["failed"]],
        ]),
        Heading(t["positions"], 1),
    ]
    if portfolio.positions:
        blocks.append(Table(t["cols_pos"], [
            [p.ticker, p.name or "", f"{p.quantity:,}", f"{p.available_quantity:,}", _money(p.avg_cost),
             _money(p.last_price), _money(p.market_value), _money(p.unrealized_pnl), _pct(p.weight)]
            for p in portfolio.positions]))
    else:
        blocks.append(text(t["no_positions"]))

    blocks.append(Heading(t["analyses"], 1))
    if not runs:
        blocks.append(text(t["no_runs"]))
    else:
        blocks.append(Table(t["cols_runs"], [
            [r.ticker, r.name or "", _rating(r.rating, lang), r.status, _order_text(r, t)] for r in runs]))
        for r in runs:
            blocks.append(Heading(f"{r.ticker} {r.name or ''}  {_rating(r.rating, lang)}", 2))
            if r.final_decision:
                blocks += markdown_blocks(r.final_decision, heading_offset=2)
            blocks += _risk_blocks(r.risk_check, t)

    blocks.append(Heading(t["orders"], 1))
    if orders:
        blocks.append(Table(t["cols_orders"], [
            [o.ticker, t.get(o.side, o.side), f"{o.quantity:,}", _money(float(o.price)), _money(float(o.fees)),
             o.status] for o in orders]))
    else:
        blocks.append(text(t["no_orders"]))
    blocks.append(Para([(t["disclaimer"], False)], muted=True))
    generated = t["generated"].format(ts=f"{datetime.now():%Y-%m-%d %H:%M}")
    subtitle = f"{t['trade_date']} {day.isoformat()}  |  {generated}"
    return Report(title=t["daily"].format(brand=BRAND), subtitle=subtitle, blocks=blocks)


def run_report(run: Run, lang: str = "zh") -> Report:
    t = L[lang]
    llm = (run.options or {}).get("llm") or {}
    meta = [[t["trade_date"], str(run.trade_date)], [t["rating"], _rating(run.rating, lang)],
            [t["status"], run.status], [t["analysts"], ", ".join(run.analysts or [])]]
    if llm:
        meta.append([t["model"], f"{llm.get('provider')} · {llm.get('quick_model')} / {llm.get('deep_model')}"])
    blocks: list = [Table(["", ""], meta), Heading(t["decision"], 1)]
    blocks += markdown_blocks(run.final_decision or "-", heading_offset=1)
    blocks += _risk_blocks(run.risk_check, t)
    if run.execution:
        ex = run.execution
        blocks += [Heading(t["execution"], 3),
                   text(f"{t.get(ex['side'], ex['side'])} {ex['quantity']} @ {ex['price']}  "
                        f"({t.get(ex['status'], ex['status'])}, {t['fees']} {ex['fees'].get('total', '-')})")]
    for key, title in ((run.investment_plan, t["plan"]), (run.trader_plan, t["trader"])):
        if key:
            blocks += [Heading(title, 1), *markdown_blocks(key, heading_offset=1)]
    if run.reports:
        blocks.append(Heading(t["reports"], 1))
        for key in ("market_report", "sentiment_report", "news_report", "fundamentals_report"):
            if run.reports.get(key):
                blocks += [Heading(t[key], 2), *markdown_blocks(run.reports[key], heading_offset=2)]
    for body, title in ((run.investment_debate, t["debate"]), (run.risk_debate, t["risk_debate"])):
        if body:
            blocks += [Heading(title, 1), *markdown_blocks(body, heading_offset=2)]
    blocks.append(Para([(t["disclaimer"], False)], muted=True))
    subtitle = t["generated"].format(ts=f"{datetime.now():%Y-%m-%d %H:%M}") + f"  |  {BRAND}"
    return Report(title=t["run"].format(ticker=run.ticker, name=run.name or ""), subtitle=subtitle, blocks=blocks)
