import { AlertTriangle, ArrowRight, ShieldAlert, ShieldCheck, ShieldX } from 'lucide-react'
import type { OrderProposal, RiskCheck, RiskViolation } from '@/api/types'
import { RatingBadge, SideBadge } from '@/components/common/Badges'
import { Badge } from '@/components/ui/Badge'
import { Card, CardBody, CardHeader } from '@/components/ui/Card'
import { useI18n, useT } from '@/i18n/I18nProvider'
import type { MessageKey } from '@/i18n/store'
import { cn } from '@/lib/cn'
import { fmtCNY, fmtNumber, fmtPct, fmtPrice, fmtShares } from '@/lib/format'

/** Format one RiskCheck.reference value by the shape of its key. */
function formatReference(
  key: string,
  v: unknown,
  yesNo: [string, string],
  tx: (key: string, fallback: string) => string,
): { text: string; className?: string } {
  if (v === null || v === undefined) return { text: '—' }
  if (typeof v === 'boolean') {
    const flagged = v && (key.includes('st') || key.includes('suspend'))
    return { text: v ? yesNo[0] : yesNo[1], className: flagged ? 'text-warn' : undefined }
  }
  if (typeof v === 'number') {
    const k = key.toLowerCase()
    if (k === 'limit_up') return { text: fmtPrice(v), className: 'text-up' }
    if (k === 'limit_down') return { text: fmtPrice(v), className: 'text-down' }
    if (/pct|weight|ratio|drawdown/.test(k)) return { text: fmtPct(v) }
    if (/price|close|open|high|low|limit/.test(k)) return { text: fmtPrice(v) }
    if (/cash|equity|notional|value|reserve|amount|fee/.test(k)) return { text: fmtCNY(v) }
    if (/qty|quantity|shares|lot|orders|count|held|available/.test(k)) return { text: fmtShares(v) }
    return { text: Number.isInteger(v) ? String(v) : fmtNumber(v, 4) }
  }
  if (typeof v === 'string') return { text: key === 'board' ? tx(`board.${v}`, v) : v }
  return { text: JSON.stringify(v) }
}

export function OrderTable({ order }: { order: OrderProposal }) {
  const t = useT()
  const weightClass =
    order.target_weight > order.current_weight ? 'text-up' : order.target_weight < order.current_weight ? 'text-down' : ''
  const rows: Array<[MessageKey, ReactNode]> = [
    ['order.ticker', <span className="font-mono">{order.ticker}</span>],
    ['order.side', <SideBadge side={order.side} />],
    ['order.quantity', <span className="font-mono">{t('common.shares', { n: fmtShares(order.quantity) })}</span>],
    ['order.refPrice', <span className="font-mono">¥{fmtPrice(order.price)}</span>],
    ['order.notional', <span className="font-mono">{fmtCNY(order.notional)}</span>],
    ['order.estFees', <span className="font-mono">{fmtCNY(order.est_fees)}</span>],
    [
      'order.weightChange',
      <span className="inline-flex items-center gap-1 font-mono">
        {fmtPct(order.current_weight, { digits: 1 })}
        <ArrowRight className="size-3 text-muted" />
        <span className={weightClass}>{fmtPct(order.target_weight, { digits: 1 })}</span>
      </span>,
    ],
  ]
  return (
    <dl className="grid grid-cols-2 gap-px overflow-hidden rounded-lg border border-line bg-line sm:grid-cols-4">
      {rows.map(([label, value], i) => (
        <div key={label} className={cn('bg-surface px-3 py-2', i === rows.length - 1 && 'col-span-2')}>
          <dt className="text-[11px] text-muted">{t(label)}</dt>
          <dd className="mt-0.5 text-sm text-fg">{value}</dd>
        </div>
      ))}
    </dl>
  )
}

function ViolationList({ items, kind }: { items: RiskViolation[]; kind: 'block' | 'warn' }) {
  const { t, tx } = useI18n()
  if (items.length === 0) return null
  const block = kind === 'block'
  return (
    <div>
      <h3 className={cn('mb-1.5 flex items-center gap-1.5 text-xs font-semibold', block ? 'text-up' : 'text-warn')}>
        {block ? <ShieldX className="size-3.5" /> : <AlertTriangle className="size-3.5" />}
        {block ? t('risk.violations', { n: items.length }) : t('risk.warnings', { n: items.length })}
      </h3>
      <ul className="space-y-1.5">
        {items.map((v, i) => {
          const name = tx(`rule.${v.rule}`, v.rule)
          return (
            <li
              key={`${v.rule}-${i}`}
              className={cn(
                'rounded-lg border-l-4 px-3 py-2 text-sm',
                block ? 'border-up bg-up/[0.06] ring-1 ring-up/20' : 'border-warn bg-warn/[0.07] ring-1 ring-warn/20',
              )}
            >
              <span className={cn('mr-2 text-xs font-medium', block ? 'text-up' : 'text-warn')}>
                {name}
                {name !== v.rule && <span className="ml-1 font-mono text-[10px] opacity-70">{v.rule}</span>}
              </span>
              {/* the message is generated by the backend and shown as-is */}
              <span className="text-fg-2">{v.message}</span>
            </li>
          )
        })}
      </ul>
    </div>
  )
}

/** Deterministic risk gate result: proposed order, blocking violations, warnings, reference prices. */
export function RiskCheckPanel({ check }: { check: RiskCheck }) {
  const { t, tx } = useI18n()
  const ref = Object.entries(check.reference ?? {})
  const blocked = check.violations.length > 0
  const yesNo: [string, string] = [t('common.yes'), t('common.no')]
  return (
    <Card>
      <CardHeader
        title={t('risk.title')}
        subtitle={t('risk.subtitle')}
        icon={check.approved ? <ShieldCheck /> : <ShieldAlert />}
        actions={
          <>
            <RatingBadge rating={check.rating} showRaw={false} />
            {check.approved ? (
              <Badge tone="ok">{t('risk.passed')}</Badge>
            ) : blocked ? (
              <Badge tone="up">{t('risk.blocked')}</Badge>
            ) : (
              <Badge tone="muted">{t('risk.noTrade')}</Badge>
            )}
          </>
        }
      />
      <CardBody className="space-y-4">
        {check.order ? <OrderTable order={check.order} /> : <p className="text-sm text-muted">{t('risk.noOrder')}</p>}
        <ViolationList items={check.violations} kind="block" />
        <ViolationList items={check.warnings} kind="warn" />
        {ref.length > 0 && (
          <div>
            <h3 className="mb-1.5 text-xs font-semibold text-muted">{t('risk.reference')}</h3>
            <dl className="grid grid-cols-2 gap-x-4 gap-y-1.5 sm:grid-cols-3">
              {ref.map(([k, v]) => {
                const f = formatReference(k, v, yesNo, tx)
                return (
                  <div key={k} className="flex items-baseline justify-between gap-2 border-b border-dashed border-line pb-1">
                    <dt className="truncate text-xs text-muted" title={k}>
                      {tx(`ref.${k}`, k)}
                    </dt>
                    <dd className={cn('font-mono text-xs text-fg', f.className)}>{f.text}</dd>
                  </div>
                )
              })}
            </dl>
          </div>
        )}
      </CardBody>
    </Card>
  )
}
